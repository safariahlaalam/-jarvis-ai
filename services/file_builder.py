"""Build styled, well-designed downloadable files from assistant output."""
import base64
from datetime import datetime, timezone
import io
import mimetypes
import re
import zipfile
from fpdf import FPDF

_FILE_BLOCK_RE = re.compile(
    r"\[FILE:\s*([^\]]+?)\s*\]\s*(.*?)\s*\[/FILE\]",
    re.DOTALL | re.IGNORECASE,
)
_STYLE_TAG_RE = re.compile(r"^\s*\[STYLE:\s*(dark|executive)\s*\]\s*", re.IGNORECASE)

THEMES = {
    "dark": {
        "bg": (11, 17, 32),          # Deep slate navy
        "header_bg": (15, 23, 42),   # Elevated slate
        "accent": (56, 189, 248),    # Electric cyan
        "title": (248, 250, 252),    # Crisp white
        "heading": (125, 211, 252),  # Soft cyan
        "text": (226, 232, 240),     # Light slate
        "muted": (148, 163, 184),    # Muted gray-blue
        "card_bg": (20, 31, 56),     # Callout card fill
        "table_alt": (17, 26, 48),   # Zebra row fill
        "border": (51, 65, 85),      # Subtle divider
    },
    "executive": {
        "bg": (255, 255, 255),       # Pure white
        "header_bg": (15, 23, 42),   # Dark navy banner
        "accent": (2, 132, 199),     # Royal sky blue
        "title": (255, 255, 255),    # White on navy banner
        "heading": (15, 23, 42),     # Deep navy headings
        "text": (30, 41, 59),        # Charcoal body text
        "muted": (100, 116, 139),    # Slate gray
        "card_bg": (240, 249, 255),  # Ice-blue callout fill
        "table_alt": (248, 250, 252),# Soft row stripe
        "border": (203, 213, 225),   # Clean rule line
    },
}


def _safe(text: str) -> str:
    cleaned = (
        text.replace("—", "-")
        .replace("–", "-")
        .replace("“", '"')
        .replace("”", '"')
        .replace("’", "'")
        .replace("•", "-")
    )
    return cleaned.encode("latin-1", "replace").decode("latin-1")


class StyledDocumentPDF(FPDF):
    def __init__(self, doc_title: str, theme_name: str = "executive"):
        super().__init__(orientation="P", unit="mm", format="A4")
        self.doc_title = _safe(doc_title)
        self.theme = THEMES.get(theme_name, THEMES["executive"])
        self.set_margins(18, 20, 18)
        self.set_auto_page_break(auto=True, margin=18)

    def header(self):
        t = self.theme
        # Full-page background fill (essential for dark theme)
        self.set_fill_color(*t["bg"])
        self.rect(0, 0, 210, 297, style="F")

        if self.page_no() == 1:
            # Top Hero Banner
            self.set_fill_color(*t["header_bg"])
            self.rect(0, 0, 210, 40, style="F")
            # Left & bottom accent bars
            self.set_fill_color(*t["accent"])
            self.rect(0, 0, 4, 40, style="F")
            self.rect(0, 39.2, 210, 0.8, style="F")

            self.set_xy(18, 11)
            self.set_font("Helvetica", "B", 18)
            self.set_text_color(*t["title"])
            self.cell(0, 9, self.doc_title, new_x="LMARGIN", new_y="NEXT")

            stamp = datetime.now(timezone.utc).strftime("%B %d, %Y")
            self.set_x(18)
            self.set_font("Helvetica", "", 9)
            self.set_text_color(*t["accent"])
            self.cell(0, 5, f"RAMI INTELLIGENCE BRIEF  |  {stamp.upper()}", new_x="LMARGIN", new_y="NEXT")
            self.set_y(48)
        else:
            self.set_xy(18, 10)
            self.set_font("Helvetica", "B", 8)
            self.set_text_color(*t["muted"])
            self.cell(0, 5, self.doc_title.upper(), align="R", new_x="LMARGIN", new_y="NEXT")
            self.set_y(18)

    def footer(self):
        t = self.theme
        self.set_y(-13)
        self.set_draw_color(*t["border"])
        self.line(18, self.get_y(), 192, self.get_y())
        self.set_y(-11)
        self.set_font("Helvetica", "", 8)
        self.set_text_color(*t["muted"])
        self.cell(90, 5, "Generated by RAMI AI", align="L")
        self.cell(84, 5, f"Page {self.page_no()} of {{nb}}", align="R")


def _build_styled_pdf(body: str, fallback_title: str) -> bytes:
    style_match = _STYLE_TAG_RE.match(body)
    theme_name = style_match.group(1).lower() if style_match else "executive"
    content = _STYLE_TAG_RE.sub("", body).strip()

    lines = content.splitlines()
    doc_title = fallback_title
    if lines and lines[0].startswith("# "):
        doc_title = lines[0][2:].strip()
        lines = lines[1:]

    pdf = StyledDocumentPDF(doc_title=doc_title, theme_name=theme_name)
    pdf.alias_nb_pages()
    pdf.add_page()
    t = pdf.theme

    i = 0
    while i < len(lines):
        raw = lines[i].rstrip()
        stripped = raw.strip()

        if not stripped:
            pdf.ln(3)
            i += 1
            continue

        # Section Heading (##)
        if stripped.startswith("## "):
            pdf.ln(3)
            heading_text = _safe(stripped[3:].strip())
            y = pdf.get_y()
            pdf.set_fill_color(*t["accent"])
            pdf.rect(18, y + 1, 2.2, 6.5, style="F")
            pdf.set_x(23)
            pdf.set_font("Helvetica", "B", 13)
            pdf.set_text_color(*t["heading"])
            pdf.multi_cell(0, 7.5, heading_text)
            pdf.ln(1.5)
            i += 1
            continue

        # Sub-heading (###)
        if stripped.startswith("### "):
            pdf.ln(2)
            pdf.set_x(18)
            pdf.set_font("Helvetica", "B", 11)
            pdf.set_text_color(*t["accent"])
            pdf.multi_cell(0, 6.5, _safe(stripped[4:].strip()))
            pdf.ln(1)
            i += 1
            continue

        # Callout Card (> )
        if stripped.startswith("> "):
            quote_lines = []
            while i < len(lines) and lines[i].strip().startswith("> "):
                quote_lines.append(lines[i].strip()[2:])
                i += 1
            quote_text = _safe(" ".join(quote_lines))
            pdf.ln(1.5)
            start_y = pdf.get_y()
            pdf.set_x(23)
            pdf.set_font("Helvetica", "I", 10)
            pdf.set_text_color(*t["text"])
            pdf.set_fill_color(*t["card_bg"])
            pdf.multi_cell(169, 6, quote_text, fill=True)
            end_y = pdf.get_y()
            pdf.set_fill_color(*t["accent"])
            pdf.rect(18, start_y, 3, end_y - start_y, style="F")
            pdf.ln(2.5)
            continue

        # Markdown Table (| col | col |)
        if stripped.startswith("|") and "|" in stripped[1:]:
            table_rows = []
            while i < len(lines) and lines[i].strip().startswith("|"):
                row_str = lines[i].strip().strip("|")
                cells = [c.strip() for c in row_str.split("|")]
                # Skip separator row like |---|---|
                if not all(set(c) <= {"-", ":", " "} for c in cells):
                    table_rows.append(cells)
                i += 1
            if table_rows:
                pdf.ln(2)
                col_count = max(len(r) for r in table_rows)
                col_w = 174 / max(1, col_count)
                for r_idx, row in enumerate(table_rows):
                    pdf.set_x(18)
                    if r_idx == 0:
                        pdf.set_fill_color(*t["header_bg"])
                        pdf.set_text_color(*t["title"])
                        pdf.set_font("Helvetica", "B", 9.5)
                    else:
                        fill = t["table_alt"] if r_idx % 2 == 1 else t["bg"]
                        pdf.set_fill_color(*fill)
                        pdf.set_text_color(*t["text"])
                        pdf.set_font("Helvetica", "", 9.5)
                    for c_idx in range(col_count):
                        val = _safe(row[c_idx]) if c_idx < len(row) else ""
                        pdf.cell(col_w, 7.5, f" {val[:42]}", border=0, fill=True)
                    pdf.ln(7.5)
                pdf.ln(2.5)
            continue

        # Bullet Point (- or *)
        if stripped.startswith("- ") or stripped.startswith("* "):
            bullet_text = _safe(stripped[2:].replace("**", ""))
            y = pdf.get_y()
            pdf.set_fill_color(*t["accent"])
            pdf.circle(20.5, y + 3, 1.1, style="F")
            pdf.set_x(24)
            pdf.set_font("Helvetica", "", 10.5)
            pdf.set_text_color(*t["text"])
            pdf.multi_cell(0, 6, bullet_text)
            pdf.ln(0.8)
            i += 1
            continue

        # Standard Paragraph
        clean_para = _safe(stripped.replace("**", ""))
        pdf.set_x(18)
        pdf.set_font("Helvetica", "", 10.5)
        pdf.set_text_color(*t["text"])
        pdf.multi_cell(0, 6.2, clean_para)
        pdf.ln(1.2)
        i += 1

    return bytes(pdf.output())


def extract_and_build_file(reply_text: str) -> tuple[str, dict | None]:
    match = _FILE_BLOCK_RE.search(reply_text)
    if not match:
        return reply_text, None

    raw_name = match.group(1).strip().strip('"').strip("'")
    filename = re.sub(r"[^A-Za-z0-9._-]", "_", raw_name) or "rami_document.pdf"
    body = match.group(2).strip()
    ext = filename.rsplit(".", 1)[-1].lower() if "." in filename else "txt"

    if ext == "pdf":
        title_guess = filename.rsplit(".", 1)[0].replace("_", " ").title()
        raw_bytes = _build_styled_pdf(body, fallback_title=title_guess)
        mime_type = "application/pdf"
    elif ext == "zip":
        mem = io.BytesIO()
        inner_name = filename[:-4] + ".txt" if filename.lower().endswith(".zip") else "output.txt"
        with zipfile.ZipFile(mem, "w", zipfile.ZIP_DEFLATED) as zf:
            zf.writestr(inner_name, body)
        raw_bytes = mem.getvalue()
        mime_type = "application/zip"
    else:
        raw_bytes = body.encode("utf-8")
        mime_type = mimetypes.guess_type(filename)[0] or "text/plain;charset=utf-8"

    cleaned_reply = _FILE_BLOCK_RE.sub("", reply_text).strip()
    if not cleaned_reply:
        cleaned_reply = f"I have designed and prepared `{filename}` for you."

    return cleaned_reply, {
        "filename": filename,
        "mime_type": mime_type,
        "size_bytes": len(raw_bytes),
        "base64": base64.b64encode(raw_bytes).decode("ascii"),
    }
